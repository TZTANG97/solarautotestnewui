"""
WT 自动化坐标参数说明（给新人）

一、这些坐标是干什么的
- 本文件里的坐标，主要给 `SCPITestWave.py -> messured_set()` 使用。
- 自动化通过 `pyautogui` 点击 WTViewerEfree 的“数值详细设置”窗口。
- 这里记录的是“相对窗口左上角”的坐标，不是屏幕绝对坐标。

二、如何从相对坐标变成真实点击位置
- 代码里会先取设置窗口矩形：`left, top, right, bottom = GetWindowRect(...)`
- 实际点击位置 = `(left + x, top + y)`

三、CELLS_COORD_* 的数据结构（重要）
- 每个机型（WT3000/WT1800/WT1806E/WT5000）各有一份坐标模板：
  - `cells_coord[0]`：测量项目页里“批量勾选/清理”用的一组固定点。
  - `cells_coord[1]`：详细参数和测量项目的主要操作点。
    - 前几个元素通常是“测试时间、保存文件名、下拉框入口”等基础控件。
    - 后面大量元素对应各测量项目勾选框。
    - 个别元素是三元组列表（例如时分秒输入框 3 个点）。

四、维护注意事项
- 这些坐标与 WT 软件版本、Windows 缩放、分辨率、字体都强相关。
- 如果界面改版/缩放改变，点击会偏移，需要重新采点。
- 重新采点建议：固定分辨率 + 固定缩放（建议 100%）再录入。
"""

